"""Check every number in the evaluation report against the result files, with evidence-check's script.

  python tools/check_report.py [eval/EVALUATION.md]

Each sentence (and each table row) that states a number becomes a claim. Its evidence is the shortest set
of whole lines from the result files that between them hold all of its numbers; evidence-check's
`check_claim` then confirms that each quoted line is in its file and that every number of the claim is in
the quotes. Claims that cannot be backed are listed, and the exit code is 1.

Sources: eval/results/summary.md, attribution.md, checks.md, facts.md (all generated by `python -m bench
all`), the judge summaries, and eval/PREREGISTRATION.md (dates, times, predictions as registered).
"""
from __future__ import annotations

import importlib.util
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from bench import config  # noqa: E402


def load_checker():
    for p in (config.BIZ_DIR / "vendor" / "evidence-check" / "check_evidence.py",
              config.AD_REVIEW_DIR.parent / "evidence-check" / "skills" / "evidence-check" / "scripts" / "check_evidence.py"):
        if p.exists():
            spec = importlib.util.spec_from_file_location("check_evidence", p)
            m = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(m)
            return m
    sys.exit("evidence-check's check_evidence.py not found")


SOURCES = ["eval/results/summary.md", "eval/results/attribution.md", "eval/results/checks.md", "eval/results/facts.md",
           "eval/PREREGISTRATION.md", "eval/results/base/judgements.summary.json",
           "eval/results/judge-calibration/judgements.summary.json"]


STOP = {"with", "that", "this", "from", "were", "was", "the", "and", "for", "are", "per", "trial", "trials", "base", "run"}


def content_words(text: str) -> set:
    """Words of four or more letters (English, lower case) and two-character Chinese runs, minus a few common ones."""
    t = text.lower()
    out = {w for w in re.findall(r"[a-z][a-z0-9-]{3,}", t) if w not in STOP}
    for run in re.findall(r"[一-鿿]+", t):
        out |= {run[i:i + 2] for i in range(len(run) - 1)}
    return out


def claims_of(text: str) -> list[tuple[int, str]]:
    """(line number, text): every table row, and every sentence of the prose (paragraphs joined)."""
    out, para, start, in_code = [], [], 0, False
    lines = text.splitlines()

    def flush():
        if para:
            joined = " ".join(x.strip() for x in para)
            for s in re.split(r"(?<=[.;!?])\s+(?=[A-Z0-9“\"(*`|-])|(?<=[。；！？])", joined):
                if s.strip():
                    out.append((start, s.strip()))
        para.clear()

    for i, line in enumerate(lines, 1):
        if line.startswith("```"):
            in_code = not in_code
            flush()
            continue
        if in_code:
            continue
        if line.startswith("|"):
            flush()
            if not set(line) <= set("|-: "):
                out.append((i, line.strip()))
        elif not line.strip() or line.startswith("#"):
            flush()
        else:
            if not para:
                start = i
            para.append(line.lstrip("- ").strip() if line.startswith("- ") else line)
    flush()
    return out


def main(argv=None) -> int:
    ce = load_checker()
    report = Path(argv[0]) if argv else ROOT / "eval" / "EVALUATION.md"
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp)
        lines_by_file = {}
        for rel in SOURCES:
            p = ROOT / rel
            if not p.exists():
                continue
            name = rel.replace("/", "__")
            shutil.copyfile(p, src / name)
            lines_by_file[name] = [l.strip() for l in p.read_text(encoding="utf-8").splitlines() if len(l.strip()) >= 12]
        sources = ce.load_sources([str(src)])
        candidates = [(f, l, ce.numbers_in(l, generous=True)) for f, ls in lines_by_file.items() for l in ls]
        results, bad = [], []
        for line_no, text in claims_of(report.read_text(encoding="utf-8")):
            text = re.sub(r"\]\([^)]*\)", "]", text)          # link targets are not claims
            text = re.sub(r"https?://\S+", "", text)
            need = ce.numbers_in(text)
            if not need:
                continue
            left, chosen = set(need), []
            words = content_words(text)
            overlap = lambda c: len(words & content_words(c[1]))
            # Only lines that share at least two content words with the claim can back it: a line that happens to
            # hold the same number but is about something else does not count.
            ids = {w for w in words if re.search(r"\d", w) and "-" in w}  # check and task ids such as k-bz-2, en-l2-01
            exact = [c for c in candidates if c[1] == text]  # a table row copied from a result file
            pool = exact or [c for c in candidates if overlap(c) >= 2 or (ids & content_words(c[1]))]
            if not pool and re.search(r"[一-鿿]", text) and len(need) >= 2:
                # a Chinese sentence against English result files: only a single line holding every one of its numbers
                pool = [c for c in candidates if need <= c[2]]
            while left and pool:
                best = max(pool, key=lambda c: (len(c[2] & left), overlap(c), -len(c[1])))
                if not best[2] & left:
                    break
                chosen.append(best)
                left -= best[2]
            claim = {"id": f"L{line_no}", "text": text, "evidence": [{"source": f, "quote": q} for f, q, _ in chosen]}
            r = ce.check_claim(claim, sources) if chosen else {"status": "no_evidence", "missing_numbers": sorted(need)}
            results.append({"line": line_no, "text": text, "status": r["status"], "missing": r.get("missing_numbers", []),
                            "evidence": claim["evidence"]})
            if r["status"] != "supported":
                bad.append(results[-1])
    n = len(results)
    print(f"{n} sentences and table rows with numbers checked: {n - len(bad)} supported, {len(bad)} not")
    for b in bad:
        print(f"  line {b['line']}: {b['status']} {b['missing']} | {b['text'][:150]}")
    out = ROOT / "eval" / "results" / f"report-check-{report.stem}.json"
    out.write_text(json.dumps({"report": report.name, "checked": n, "supported": n - len(bad), "problems": bad, "claims": results}, ensure_ascii=False, indent=1)
                   + "\n", encoding="utf-8", newline="\n")
    return 1 if bad else 0


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main(sys.argv[1:]))
